'use client';

import { WebSource } from '@/lib/types';

export interface ResearchBrief {
  id: string;
  title: string;
  topic: string;
  depth: 'standard' | 'deep' | 'comprehensive';
  objectives: string[];
  synthesis: string;
  keyFindings: string[];
  counterArguments?: string[];
  sources: WebSource[];
  takeaways: string[];
  createdAt: string;
  updatedAt: string;
}

const RESEARCH_STORAGE_KEY = 'nyra_research_briefs';

export function getResearchBriefs(): ResearchBrief[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(RESEARCH_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    console.error('Failed to load research briefs:', e);
    return [];
  }
}

export function saveResearchBriefs(briefs: ResearchBrief[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(RESEARCH_STORAGE_KEY, JSON.stringify(briefs));
    window.dispatchEvent(new CustomEvent('nyra_research_updated', { detail: briefs }));
  } catch (e) {
    console.error('Failed to save research briefs:', e);
  }
}

export function saveResearchBrief(brief: ResearchBrief): void {
  const all = getResearchBriefs().filter((b) => b.id !== brief.id);
  saveResearchBriefs([brief, ...all]);
}

export function deleteResearchBrief(id: string): boolean {
  const all = getResearchBriefs().filter((b) => b.id !== id);
  saveResearchBriefs(all);
  return true;
}

export function exportBriefAsMarkdown(brief: ResearchBrief): string {
  const sourcesMd = brief.sources.map((s, i) => `${i + 1}. [${s.title}](${s.url})`).join('\n');
  const findingsMd = brief.keyFindings.map((f) => `- ${f}`).join('\n');
  const takeawaysMd = brief.takeaways.map((t) => `- ${t}`).join('\n');

  return `# ${brief.title}
*Research Brief generated by Nyra AI Workspace on ${new Date(brief.createdAt).toLocaleDateString()}*

## Topic & Focus
${brief.topic}

## Executive Summary & Deep Synthesis
${brief.synthesis}

## Key Discoveries & Findings
${findingsMd || 'No specific findings recorded.'}

## Key Takeaways & Recommendations
${takeawaysMd || 'None recorded.'}

## References & Sources
${sourcesMd || 'No direct web sources referenced.'}
`;
}
